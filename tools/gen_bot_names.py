#!/usr/bin/env python3
"""Makes the two tables of computer players' names from the one list tools/bot_names.txt. Pure python 3 standard library.

usage: gen_bot_names.py [--check] [--root DIR]

  (no option)  writes src/ants_ai/bot_names_data.inc (the C++ table: it is #included inside the array of src/ants_ai/bot_names.cpp) and replaces the generated block of
               web/front/bot_names.js (between the lines "BEGIN GENERATED" and "END GENERATED"; the rest of that file is written by hand)
  --check      writes nothing; exit 1 when either file differs from what the generator makes (tests/scripts/test_bot_names.py runs it, so a list that was edited without
               running the generator fails the quick tier)

Exit 0 when done or in order, 1 for a difference (--check) or a list that breaks its own rules, 2 for a usage error. The rules of the list that the generator itself enforces (the
quality tests in tests/scripts/test_bot_names.py and tests/test_ai/test_ai_names.cpp add the blocklist and the web placeholders): a name is a capital letter and 2 to 7 small
ASCII letters, no two names are the same in any case, the list has 240 to 260 names. The ORDER of the file is kept (it is part of the picker; see the top of tools/bot_names.txt).
"""
import argparse
import os
import re
import sys

LIST = "tools/bot_names.txt"
INC = "src/ants_ai/bot_names_data.inc"
JS = "web/front/bot_names.js"
BEGIN = "    // BEGIN GENERATED by tools/gen_bot_names.py from tools/bot_names.txt: do not edit this block\n"
END = "    // END GENERATED\n"
NAME = re.compile(r"^[A-Z][a-z]{2,7}$")
MIN_NAMES = 240
MAX_NAMES = 260
PER_LINE = 8


def read_names(text):
    """The names of the list file, in order. Raises ValueError with a message for a list that breaks a rule."""
    names = []
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if not NAME.match(line):
            raise ValueError("%s line %d: %r is not a capital letter and 2 to 7 small ASCII letters" % (LIST, number, line))
        names.append(line)
    seen = {}
    for name in names:
        if name.lower() in seen:
            raise ValueError("%s: %r and %r are the same name in different case" % (LIST, seen[name.lower()], name))
        seen[name.lower()] = name
    if not MIN_NAMES <= len(names) <= MAX_NAMES:
        raise ValueError("%s: %d names; the list has %d to %d" % (LIST, len(names), MIN_NAMES, MAX_NAMES))
    return names


def rows(names, quote_end):
    """The names, PER_LINE to a row, as quoted words followed by commas."""
    out = []
    for i in range(0, len(names), PER_LINE):
        out.append(" ".join('"%s"%s' % (n, quote_end) for n in names[i:i + PER_LINE]))
    return out


def render_inc(names):
    head = ("// GENERATED by tools/gen_bot_names.py from tools/bot_names.txt: do not edit (edit the list and run the generator; a test compares this file with what it makes).\n"
            "// %d names, the initializers of kBotNames in bot_names.cpp.\n" % len(names))
    return head + "\n".join(rows(names, ",")) + "\n"


def render_js_block(names):
    lines = ["    var NAMES = ["]
    body = rows(names, ",")
    body[-1] = body[-1].rstrip(",")
    lines += ["        " + r for r in body]
    lines.append("    ];")
    return BEGIN + "\n".join(lines) + "\n" + END


def splice_js(text, names):
    """The text of bot_names.js with its generated block replaced. Raises ValueError when the markers are not there exactly once."""
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        raise ValueError("%s: the generated block (BEGIN GENERATED ... END GENERATED) must be there exactly once" % JS)
    a = text.index(BEGIN)
    b = text.index(END) + len(END)
    return text[:a] + render_js_block(names) + text[b:]


def read(root, rel):
    with open(os.path.join(root, rel), encoding="utf-8", newline="") as f:
        return f.read()


def write(root, rel, text):
    with open(os.path.join(root, rel), "w", encoding="utf-8", newline="") as f:
        f.write(text)


def main(argv):
    parser = argparse.ArgumentParser(description="Makes the C++ and JavaScript tables of computer players' names from tools/bot_names.txt.")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 when a generated file differs")
    parser.add_argument("--root", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."), help="the checkout (default: this script's)")
    args = parser.parse_args(argv[1:])
    root = os.path.abspath(args.root)
    try:
        names = read_names(read(root, LIST))
        wanted = {INC: render_inc(names), JS: splice_js(read(root, JS), names)}
    except (OSError, ValueError) as e:
        print("gen_bot_names: %s" % e, file=sys.stderr)
        return 1
    bad = 0
    for rel, text in wanted.items():
        current = read(root, rel) if os.path.exists(os.path.join(root, rel)) else None
        if args.check:
            if current != text:
                print("gen_bot_names: %s is not what tools/gen_bot_names.py makes from %s (run it without --check)" % (rel, LIST), file=sys.stderr)
                bad += 1
        elif current != text:
            write(root, rel, text)
            print("wrote %s" % rel)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
