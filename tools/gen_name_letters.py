#!/usr/bin/env python3
"""Makes the game's table and the page's table of the letters of a name from the one table hub/name_letters.py. Pure python 3 standard library.

usage: gen_name_letters.py [--check] [--root DIR]

  (no option)  writes src/ants_net/name_letters_data.inc (the C++ table: it is #included inside the array of src/ants_net/name_rules.cpp) and replaces the generated block of
               web/front/name_letters.js (between the lines "BEGIN GENERATED" and "END GENERATED"; the rest of that file is written by hand)
  --check      writes nothing; exit 1 when either file differs from what the generator makes (tests/scripts/test_name_letters.py runs it, so a table that was edited without running
               the generator fails the quick tier)

Exit 0 when done or in order, 1 for a difference (--check) or a table that breaks its own rules, 2 for a usage error.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
INC = "src/ants_net/name_letters_data.inc"
JS = "web/front/name_letters.js"
BEGIN = "    // BEGIN GENERATED by tools/gen_name_letters.py from hub/name_letters.py: do not edit this block\n"
END = "    // END GENERATED\n"


def table(root):
    sys.path.insert(0, root)
    sys.modules.pop("hub.name_letters", None)
    sys.modules.pop("hub", None)
    from hub import name_letters
    rows = []
    for index, name in enumerate(name_letters.ALPHABETS):
        for first, last in name_letters.ALPHABETS[name]:
            if first > last:
                raise ValueError("hub/name_letters.py: the range %X - %X is backwards" % (first, last))
            rows.append((first, last, index, name))
    rows.sort()
    for before, after in zip(rows, rows[1:]):
        if after[0] <= before[1]:
            raise ValueError("hub/name_letters.py: the ranges %X - %X and %X - %X overlap" % (before[0], before[1], after[0], after[1]))
    return rows


def render_inc(rows):
    head = ("// GENERATED by tools/gen_name_letters.py from the table of the letters of a name: do not edit (edit the table and run the generator; a test compares this file with what it makes).\n"
            "// The letters of a name, sorted: { first, last, alphabet } with the alphabet 0 for Latin and 1 for Cyrillic; the initializers of kNameLetters in name_rules.cpp.\n")
    return head + "".join("{0x%X, 0x%X, %d},  // %s\n" % (first, last, index, name) for first, last, index, name in rows)


def render_js_block(rows):
    lines = ["    var RANGES = ["]
    for i, (first, last, index, name) in enumerate(rows):
        lines.append("        [0x%X, 0x%X, %d]%s" % (first, last, index, "," if i + 1 < len(rows) else ""))
    lines.append("    ];       // [first, last, alphabet] sorted: 0 Latin, 1 Cyrillic")
    return BEGIN + "\n".join(lines) + "\n" + END


def splice_js(text, rows):
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        raise ValueError("%s: the generated block (BEGIN GENERATED ... END GENERATED) must be there exactly once" % JS)
    a = text.index(BEGIN)
    b = text.index(END) + len(END)
    return text[:a] + render_js_block(rows) + text[b:]


def read(root, rel):
    with open(os.path.join(root, rel), encoding="utf-8", newline="") as f:
        return f.read()


def write(root, rel, text):
    with open(os.path.join(root, rel), "w", encoding="utf-8", newline="") as f:
        f.write(text)


def main(argv):
    parser = argparse.ArgumentParser(description="Makes the C++ and JavaScript tables of the letters of a name from hub/name_letters.py.")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 when a generated file differs")
    parser.add_argument("--root", default=os.path.join(HERE, ".."), help="the checkout (default: this script's)")
    args = parser.parse_args(argv[1:])
    root = os.path.abspath(args.root)
    try:
        rows = table(root)
        wanted = {INC: render_inc(rows), JS: splice_js(read(root, JS), rows)}
    except (OSError, ValueError, ImportError) as e:
        print("gen_name_letters: %s" % e, file=sys.stderr)
        return 1
    bad = 0
    for rel, text in wanted.items():
        current = read(root, rel) if os.path.exists(os.path.join(root, rel)) else None
        if args.check:
            if current != text:
                print("gen_name_letters: %s is not what tools/gen_name_letters.py makes from hub/name_letters.py (run it without --check)" % rel, file=sys.stderr)
                bad += 1
        elif current != text:
            write(root, rel, text)
            print("wrote %s" % rel)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
