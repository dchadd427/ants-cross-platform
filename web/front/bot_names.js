    var LABEL_NAME_MAX = 16;                                           // include/ants_ai/bot_names.hpp kBotLabelNameMax
    var TAGS = { easy: 'Easy', medium: 'Medium', hard: 'Hard', idle: 'idle', worker: 'worker' };
    var LEGACY = { 'Bot (Easy)': 'easy', 'Bot (Medium)': 'medium', 'Bot (Hard)': 'hard', 'Bot (Idle)': 'idle', 'Bot (Worker)': 'worker' };

    // ---- 64-bit arithmetic on [high, low] pairs of unsigned 32-bit numbers (mix64 of include/ants_ai/rng.hpp, the finalizer of splitmix64) -------------------------------------------------
    function xor64(a, b) { return [(a[0] ^ b[0]) >>> 0, (a[1] ^ b[1]) >>> 0]; }
    function add64(a, b) {
        var lo = a[1] + b[1];
        return [(a[0] + b[0] + (lo > 4294967295 ? 1 : 0)) >>> 0, lo >>> 0];
    }
    function shr64(a, n) { return [a[0] >>> n, ((a[1] >>> n) | (a[0] << (32 - n))) >>> 0]; }          // (0 < n < 32)
    function limbs(a) { return [a[1] & 0xFFFF, a[1] >>> 16, a[0] & 0xFFFF, a[0] >>> 16]; }
    function mul64(a, b) {                                                                               // (a * b) mod 2^64, with 16-bit limbs so that every product and sum is exact
        var x = limbs(a), y = limbs(b), r = [0, 0, 0, 0], carry = 0, i, j, sum;
        for (i = 0; i < 4; i++) {
            sum = carry;
            for (j = 0; j <= i; j++) sum += x[j] * y[i - j];
            r[i] = sum % 65536;
            carry = Math.floor(sum / 65536);
        }
        return [((r[3] << 16) | r[2]) >>> 0, ((r[1] << 16) | r[0]) >>> 0];
    }
    var C1 = [0xBF58476D, 0x1CE4E5B9], C2 = [0x94D049BB, 0x133111EB];
    function mix64(z) {
        z = mul64(xor64(z, shr64(z, 30)), C1);
        z = mul64(xor64(z, shr64(z, 27)), C2);
        return xor64(z, shr64(z, 31));
    }
    function mod64(a, n) { return ((a[0] % n) * (4294967296 % n) + (a[1] % n)) % n; }                  // (n below 2^21: every product is exact)

    function fail(Kind, why, key) { throw new Kind('bot_names: ' + why + ' (' + (typeof key === 'bigint' ? 'a BigInt' : typeof key === 'string' ? JSON.stringify(key) : String(key)) + ')'); }
    function keyOf(key) {
        if (typeof key === 'string') {
            var m = /^(?:0[xX])?([0-9a-fA-F]{1,16})$/.exec(key);
            if (!m) fail(TypeError, 'a key string must be 1 to 16 hexadecimal digits', key);
            var h = ('0000000000000000' + m[1]).slice(-16);
            return [parseInt(h.slice(0, 8), 16) >>> 0, parseInt(h.slice(8), 16) >>> 0];
        }
        if (typeof key === 'number') {
            if (key !== key || key === Infinity || key === -Infinity || Math.floor(key) !== key) fail(TypeError, 'a key number must be a whole number', key);
            if (key < 0 || key > 9007199254740991) fail(RangeError, 'a key number must be from 0 to 2^53 - 1 (give a larger key as a string of hexadecimal digits)', key);
            return [Math.floor(key / 4294967296) >>> 0, key % 4294967296 >>> 0];
        }
        if (Object.prototype.toString.call(key) === '[object Array]' && key.length === 2) {
            var i, v;
            for (i = 0; i < 2; i++) {
                v = key[i];
                if (typeof v !== 'number' || Math.floor(v) !== v || v < 0 || v > 4294967295) fail(RangeError, 'a key pair holds two whole numbers from 0 to 2^32 - 1', key);
            }
            return [key[0] >>> 0, key[1] >>> 0];
        }
        return fail(TypeError, 'a key is a hexadecimal string, a whole number or a pair [high, low]', key);
    }
    // the lower case of A-Z only (String.toLowerCase also maps the Kelvin sign to "k", the Turkish capital i and others)
    function asciiLower(text) { return text.replace(/[A-Z]/g, function (c) { return String.fromCharCode(c.charCodeAt(0) + 32); }); }

    // ---- the picker ---------------------------------------------------------------------------------------------------------------------------------------------------------------------------
    var PICK_SEED = [0xB07A11E5, 0xB07A11E5], PICK_STEP = [0x9E3779B9, 0x7F4A7C15];
    // `count` DISTINCT names for a key: the i-th draw is a fresh hash of (key, i); a draw that repeats a name is skipped, so pickBotNames(k, 2) is the first two of pickBotNames(k, 3).
    function pickBotNames(key, count) {
        var want = Math.floor(Number(count));
        want = isFinite(want) ? Math.min(Math.max(want, 0), NAMES.length) : 0;
        var out = [], used = {}, base = mix64(xor64(keyOf(key), PICK_SEED)), draw, index;
        for (draw = 1; out.length < want; draw++) {
            index = mod64(mix64(add64(base, mul64([0, draw], PICK_STEP))), NAMES.length);
            if (used[index]) continue;
            used[index] = true;
            out.push(NAMES[index]);
        }
        return out;
    }

    // ---- the label, its parser and the reserved-name rule -----------------------------------------------------------------------------------------------------------------------------
    function validLabelName(name) {
        return typeof name === 'string' && name.length >= 1 && name.length <= LABEL_NAME_MAX && name.charAt(0) !== ' ' && name.charAt(name.length - 1) !== ' ' && /^[\x20-\x27\x2a-\x7e]*$/.test(name);
    }
    // "Pip (bot, Hard)"; "Pip (bot, idle)" and "Pip (bot, worker)" for the two test kinds. `tag` is easy, medium, hard, idle or worker in any case. A name that is not valid gives the legacy
    // label ("Bot (Hard)"), so a bot is never shown without a name; a tag that is none of the five gives ''.
    function botLabel(name, tag) {
        var k = typeof tag === 'string' ? asciiLower(tag) : '';
        if (!Object.prototype.hasOwnProperty.call(TAGS, k)) return '';
        var word = TAGS[k];
        if (!validLabelName(name)) return 'Bot (' + (word === 'idle' ? 'Idle' : word === 'worker' ? 'Worker' : word) + ')';
        return name + ' (bot, ' + word + ')';
    }
    // { name, tag, legacy } for "Pip (bot, Hard)", the short form "Pip (bot)" (tag '') and the five legacy labels (name ''), else null. The spelling must be exactly that of botLabel.
    function parseBotLabel(text) {
        if (typeof text !== 'string') return null;
        if (Object.prototype.hasOwnProperty.call(LEGACY, text)) return { name: '', tag: LEGACY[text], legacy: true };
        if (text.charAt(text.length - 1) !== ')') return null;
        var open = text.lastIndexOf(' (bot');
        if (open < 0) return null;
        var name = text.slice(0, open), inside = text.slice(open + 5, text.length - 1), tag = '', k;
        if (inside !== '') {
            if (inside.slice(0, 2) !== ', ') return null;
            var word = inside.slice(2);
            for (k in TAGS) if (Object.prototype.hasOwnProperty.call(TAGS, k) && TAGS[k] === word) tag = k;
            if (tag === '') return null;
        }
        return validLabelName(name) ? { name: name, tag: tag, legacy: false } : null;
    }
    // The short form for a narrow place (the HUD's label is cut at 15 characters): "Pip (bot)" for a label in the new form, the text unchanged for anything else
    function botShortLabel(text) {
        var p = parseBotLabel(text);
        return p && !p.legacy ? p.name + ' (bot)' : text;
    }
    // Whether a PERSON may not be called `text`: a name that starts with "Bot (" (legacy) or ends with "(bot)" or "(bot, ...)" (any words between the comma and the parenthesis). Blanks (also tabs and line ends) and case are ignored.
    function isReservedBotName(text) {
        var s = typeof text === 'string' ? asciiLower(text.replace(/[ \t\r\n]/g, '')) : '';
        if (s.indexOf('bot(') === 0) return true;
        if (s.charAt(s.length - 1) !== ')') return false;
        var open = s.lastIndexOf('(');
        if (open < 0) return false;
        var inside = s.slice(open + 1, s.length - 1);
        if (inside === 'bot') return true;
        return inside.indexOf('bot,') === 0 && inside.length > 4 && inside.indexOf(')') < 0;
    }

    // for the tests: the 64-bit finalizer on a key given as in keyOf, as 16 hexadecimal digits
    function mix64Hex(key) {
        var z = mix64(keyOf(key)), h = z[0].toString(16), l = z[1].toString(16);
        return ('00000000' + h).slice(-8) + ('00000000' + l).slice(-8);
    }

