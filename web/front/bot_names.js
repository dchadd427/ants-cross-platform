    function xor64(a, b) { return [(a[0] ^ b[0]) >>> 0, (a[1] ^ b[1]) >>> 0]; }
    function add64(a, b) {
        var lo = a[1] + b[1];
        return [(a[0] + b[0] + (lo > 4294967295 ? 1 : 0)) >>> 0, lo >>> 0];
    }
    function shr64(a, n) { return [a[0] >>> n, ((a[1] >>> n) | (a[0] << (32 - n))) >>> 0]; }          // (0 < n < 32)
    function limbs(a) { return [a[1] & 0xFFFF, a[1] >>> 16, a[0] & 0xFFFF, a[0] >>> 16]; }
    function mul64(a, b) {                                                                               // (a * b) mod 2^64, with 16-bit limbs so that every product and sum is exact
        var x = limbs(a), y = limbs(b), r = [0, 0, 0, 0], carry = 0, i, j, sum;
        for (i = 0; i < 4; i++) {
            sum = carry;
            for (j = 0; j <= i; j++) sum += x[j] * y[i - j];
            r[i] = sum % 65536;
            carry = Math.floor(sum / 65536);
        }
        return [((r[3] << 16) | r[2]) >>> 0, ((r[1] << 16) | r[0]) >>> 0];
    }
