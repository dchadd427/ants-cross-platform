// The letters of a name, and names as UTF-8 (docs/HUB_NICKNAMES.md, "The letters"; tests/scripts/test_name_letters.py). The table is hub/name_letters.py: the generated block below is made from it by
// tools/gen_name_letters.py (a test fails when it differs). A name goes over the wire as UTF-8: printable ASCII and the letters of the table, at most 32 characters and 96 bytes, which is what
// the game's decoders accept (src/ants_net/name_rules.cpp is the twin of this file; tests/scripts/web_name_letters_check.js holds both to the same cases). It also takes a shown name apart (split) and draws it (paint):
// the game has one plain string, "[TAG] Nickname" or "Name (Guest)", and every page shows the tag and the "(Guest)" dimmer than the name (docs/HUB_NICKNAMES.md, "Where a name shows").
//   * ES5, no module system: a page gets the global AntsNameLetters, node gets module.exports. A text from strangers is read one code point at a time; a lone surrogate is never a letter.
(function (root, factory) {
    var api = factory();
    if (typeof module === 'object' && module.exports) module.exports = api;
    else root.AntsNameLetters = api;
})(typeof self !== 'undefined' ? self : this, function () {
    'use strict';

    var MAX_NAME_CHARS = 32;           // a name on the wire: code points (net::kMaxNameChars) ...
    var MAX_NAME_BYTES = 96;           // ... and bytes (net::kMaxNameBytes)
    // BEGIN GENERATED by tools/gen_name_letters.py from hub/name_letters.py: do not edit this block
    var RANGES = [
        [0x41, 0x5A, 0],
        [0x61, 0x7A, 0],
        [0xC0, 0xD6, 0],
        [0xD8, 0xF6, 0],
        [0xF8, 0xFF, 0],
        [0x100, 0x17E, 0],
        [0x1A0, 0x1A1, 0],
        [0x1AF, 0x1B0, 0],
        [0x218, 0x21B, 0],
        [0x400, 0x45F, 1],
        [0x490, 0x491, 1],
        [0x1EA0, 0x1EF9, 0]
    ];       // [first, last, alphabet] sorted: 0 Latin, 1 Cyrillic
    // END GENERATED

    // 0 for a Latin letter, 1 for a Cyrillic letter, -1 for anything else (a digit, a sign, a letter of another script)
    function alphabetOf(cp) {
        var lo = 0, hi = RANGES.length - 1, mid;
        while (lo <= hi) {
            mid = (lo + hi) >> 1;
            if (cp < RANGES[mid][0]) hi = mid - 1;
            else if (cp > RANGES[mid][1]) lo = mid + 1;
            else return RANGES[mid][2];
        }
        return -1;
    }
    function isLetter(cp) { return alphabetOf(cp) >= 0; }
    // a character that may stand in a name on the wire: printable ASCII or a letter of the table
    function isWireCodePoint(cp) { return (cp >= 0x20 && cp <= 0x7E) || alphabetOf(cp) >= 0; }

    // The code points of a string, or null when it holds a lone surrogate (it is no text: it cannot be UTF-8)
    function codePoints(text) {
        var out = [], i, c, d;
        if (typeof text !== 'string') return null;
        for (i = 0; i < text.length; i++) {
            c = text.charCodeAt(i);
            if (c >= 0xD800 && c <= 0xDBFF) {
                d = i + 1 < text.length ? text.charCodeAt(i + 1) : 0;
                if (d < 0xDC00 || d > 0xDFFF) return null;
                c = 0x10000 + ((c - 0xD800) << 10) + (d - 0xDC00);
                i++;
            } else if (c >= 0xDC00 && c <= 0xDFFF) return null;
            out.push(c);
        }
        return out;
    }
    // The UTF-8 bytes of a string whose code points are given (as an array of numbers)
    function utf8Of(points) {
        var out = [], i, c;
        for (i = 0; i < points.length; i++) {
            c = points[i];
            if (c < 0x80) out.push(c);
            else if (c < 0x800) out.push(0xC0 | (c >> 6), 0x80 | (c & 63));
            else if (c < 0x10000) out.push(0xE0 | (c >> 12), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
            else out.push(0xF0 | (c >> 18), 0x80 | ((c >> 12) & 63), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
        }
        return out;
    }
    // The string of strict UTF-8 bytes (an array or a Uint8Array), or null: no overlong form, no surrogate, nothing above U+10FFFF, no cut sequence
    function fromUtf8(bytes) {
        var s = '', i = 0, n = bytes.length, b, need, c, min, k;
        while (i < n) {
            b = bytes[i++];
            if (b < 0x80) { s += String.fromCharCode(b); continue; }
            if (b >= 0xC2 && b <= 0xDF) { need = 1; c = b & 0x1F; min = 0x80; }
            else if (b >= 0xE0 && b <= 0xEF) { need = 2; c = b & 0x0F; min = 0x800; }
            else if (b >= 0xF0 && b <= 0xF4) { need = 3; c = b & 0x07; min = 0x10000; }
            else return null;
            if (i + need > n) return null;
            for (k = 0; k < need; k++) {
                b = bytes[i++];
                if ((b & 0xC0) !== 0x80) return null;
                c = (c << 6) | (b & 63);
            }
            if (c < min || c > 0x10FFFF || (c >= 0xD800 && c <= 0xDFFF)) return null;
            s += c < 0x10000 ? String.fromCharCode(c) : String.fromCharCode(0xD800 + ((c - 0x10000) >> 10), 0xDC00 + ((c - 0x10000) & 0x3FF));
        }
        return s;
    }
    // Whether a string is a name that the wire takes: every character printable ASCII or a letter of the table, at most MAX_NAME_CHARS of them (the bytes then are at most 96 as well: a letter is 2 or 3 bytes)
    function isWireName(text, maxChars) {
        var points = codePoints(text), i;
        if (!points || points.length > (maxChars || MAX_NAME_CHARS)) return false;
        for (i = 0; i < points.length; i++) { if (!isWireCodePoint(points[i])) return false; }
        return utf8Of(points).length <= MAX_NAME_BYTES;
    }
    // The characters of a string that a name on the wire may hold, at most `max` of them (the page's own cut, as the game's client makes it: what is not in the table is left out)
    function wireOnly(text, max) {
        var points = codePoints(typeof text === 'string' ? text : ''), out = [], i;
        if (!points) return '';
        for (i = 0; i < points.length && out.length < (max || MAX_NAME_CHARS); i++) { if (isWireCodePoint(points[i])) out.push(points[i]); }
        while (out.length && utf8Of(out).length > MAX_NAME_BYTES) out.pop();
        return String.fromCodePoint ? String.fromCodePoint.apply(null, out) : out.map(function (c) { return String.fromCharCode(c); }).join('');
    }

    // ---- a shown name in its parts ----
    var TAG = /^\[([^\]\s]{2,5})\] (.+)$/, GUEST = /^(.+?)( \(Guest\))$/;
    // { tag: "[ANT]" or '', name: "Zoe", guest: " (Guest)" or '' } of a name as the game and the hub write it: a tag before it ("[TAG] Nickname"), or " (Guest)" after it. A name that is neither is all name.
    function split(name) {
        var text = typeof name === 'string' ? name : '', tag = '', guest = '', m = TAG.exec(text);
        if (m) { tag = '[' + m[1] + ']'; text = m[2]; }
        m = GUEST.exec(text);
        if (m) { text = m[1]; guest = m[2]; }
        return { tag: tag, name: text, guest: guest };
    }
    // The first character of a name as the letter of a circle: of the name without its tag, in capitals ('?' for none); a letter of the table is one code point
    function initial(name) {
        var parts = split(name), points = codePoints(parts.name) || [];
        if (!points.length) return '?';
        var letter = String.fromCodePoint ? String.fromCodePoint(points[0]) : String.fromCharCode(points[0]);
        return letter.toUpperCase();
    }
    // Draws a name into a node as text only: the tag in a span of the class `nm-tag`, the name as it is, " (Guest)" in a span of the class `nm-guest` (the style makes both dimmer); nothing in it is markup
    function paint(doc, node, name) {
        var parts = split(name), span;
        node.textContent = '';
        if (parts.tag) {
            span = doc.createElement('span'); span.className = 'nm-tag'; span.textContent = parts.tag;
            node.appendChild(span);
            node.appendChild(doc.createTextNode(' '));
        }
        node.appendChild(doc.createTextNode(parts.name));
        if (parts.guest) {
            span = doc.createElement('span'); span.className = 'nm-guest'; span.textContent = parts.guest;
            node.appendChild(span);
        }
        return node;
    }

    return {
        split: split, initial: initial, paint: paint,
        MAX_NAME_CHARS: MAX_NAME_CHARS, MAX_NAME_BYTES: MAX_NAME_BYTES, RANGES: RANGES, alphabetOf: alphabetOf, isLetter: isLetter, isWireCodePoint: isWireCodePoint,
        codePoints: codePoints, utf8Of: utf8Of, fromUtf8: fromUtf8, isWireName: isWireName, wireOnly: wireOnly
    };
});
